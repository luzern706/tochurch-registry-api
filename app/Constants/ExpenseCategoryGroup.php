namespace App\Constants;

/**
 * 예산(reg_budgets) 대분류 7종과 지출(reg_expense_records) 세부 항목 26종 간의 매핑.
 *
 * 예산은 대분류(인건비/사역비/운영비/시설비/선교비/행사비/예비비) 단위로 설정하고,
 * 실제 지출은 세부 항목 단위로 기록되므로 "집행액"을 계산하려면 이 매핑이 필요하다.
 * 사용자 확인 완료(2026-08-09) — 외부강사/세모승격금→인건비, 대출이자/차입상환→운영비 분류 포함.
 */
class ExpenseCategoryGroup
{
    /** 예산 대분류 표시 순서 (원본 mock 표 순서) */
    const ORDER = ['인건비', '사역비', '운영비', '시설비', '선교비', '행사비', '예비비'];

    /** 대분류 => 소속 지출 세부 항목 목록. 예비비는 대응되는 세부 항목이 없음(적립 성격). */
    const GROUPS = [
        '인건비' => ['담임목사', '목회비', '부교역자', '외부강사', '성악금', '세모승격금', '복리후생', '퇴직적립'],
        '사역비' => ['예배비', '기관운영(교육부서)', '기관운영(기타)', '교육비', '심방·전도비', '주일식대', '꽃꽂이'],
        '운영비' => ['사무관리비', '자동차경비', '자동차부금', '대출이자', '차입상환', '상화비'],
        '시설비' => ['교회시설비용', '보험료'],
        '선교비' => ['선교', '구제·제경사'],
        '행사비' => ['행사비'],
        '예비비' => [],
    ];

    public static function groupOf(string $category): ?string
    {
        foreach (self::GROUPS as $group => $items) {
            if (in_array($category, $items, true)) {
                return $group;
            }
        }
        return null;
    }
}
